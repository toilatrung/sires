export type PathProblem = 'empty' | 'absolute' | 'parent' | 'backslash' | 'emptySegment' | 'duplicate';

/** Path rule of ManuscriptFile.path, checked before sending (H9, EC08, EC09). */
export function pathProblem(path: string, existing: readonly string[] = []): PathProblem | undefined {
  const value = path.trim();
  if (!value) return 'empty';
  if (value.startsWith('/')) return 'absolute';
  if (value.includes('\\')) return 'backslash';
  const parts = value.split('/');
  if (parts.some((part) => part === '..')) return 'parent';
  if (parts.some((part) => part === '' || part === '.')) return 'emptySegment';
  if (existing.includes(value)) return 'duplicate';
  return undefined;
}

/** Text with comments removed (a `%` not escaped as `\%`), keeping the line length up to the comment. */
export function stripComment(line: string): string {
  for (let i = 0; i < line.length; i += 1) {
    if (line[i] === '%' && (i === 0 || line[i - 1] !== '\\')) return line.slice(0, i);
  }
  return line;
}

export interface FileReference {
  /** File that contains the command. */
  path: string;
  line: number;
  command: 'input' | 'include' | 'includegraphics';
  /** Target as written, e.g. `sections/method`. */
  target: string;
}

/** Normalised target of \input, \include (adds .tex) or \includegraphics (as written). */
export function referenceTarget(reference: Pick<FileReference, 'command' | 'target'>): string {
  if (reference.command === 'includegraphics') return reference.target;
  return /\.tex$/.test(reference.target) ? reference.target : `${reference.target}.tex`;
}

/** \input, \include and \includegraphics of the given text files (MS-EDITOR-001-AC01, EC10). */
export function fileReferences(files: readonly { path: string; text: string }[]): FileReference[] {
  const found: FileReference[] = [];
  for (const file of files) {
    file.text.split('\n').forEach((raw, index) => {
      const line = stripComment(raw);
      for (const match of line.matchAll(/\\(input|include|includegraphics)(?:\[[^\]]*\])?\{([^}]+)\}/g)) {
        found.push({ path: file.path, line: index + 1, command: match[1] as FileReference['command'], target: match[2]!.trim() });
      }
    });
  }
  return found;
}

/** References pointing at `path` (a figure may be written without its extension). */
export function referencesTo(references: readonly FileReference[], path: string): FileReference[] {
  return references.filter((reference) => {
    const target = referenceTarget(reference);
    return target === path || (reference.command === 'includegraphics' && path.startsWith(`${target}.`));
  });
}

export interface CiteKey {
  key: string;
  /** 0-based offsets in the whole text. */
  from: number;
  to: number;
  line: number;
}

const CITE = /\\(?:cite|citep|citet|citeauthor|citeyear|citealp|citealt|nocite)\*?(?:\[[^\]]*\]){0,2}\{([^}]*)\}/g;

/** Every key of every cite command, with its position (UX-MS-005, EC26). */
export function citeKeys(text: string): CiteKey[] {
  const keys: CiteKey[] = [];
  let offset = 0;
  text.split('\n').forEach((raw, index) => {
    const line = stripComment(raw);
    for (const match of line.matchAll(CITE)) {
      const open = match.index! + match[0].lastIndexOf('{') + 1;
      let at = open;
      for (const part of match[1]!.split(',')) {
        const start = at + (part.length - part.trimStart().length);
        const key = part.trim();
        if (key) keys.push({ key, from: offset + start, to: offset + start + key.length, line: index + 1 });
        at += part.length + 1;
      }
    }
    offset += raw.length + 1;
  });
  return keys;
}

export interface OutlineItem {
  level: number;
  title: string;
  path: string;
  line: number;
}

/** \section-level headings of a text file, for the outline (Dàn ý). */
export function outline(path: string, text: string): OutlineItem[] {
  const items: OutlineItem[] = [];
  text.split('\n').forEach((raw, index) => {
    const match = /\\(part|chapter|section|subsection|subsubsection)\*?\{([^}]*)\}/.exec(stripComment(raw));
    if (match) items.push({ level: ['part', 'chapter', 'section', 'subsection', 'subsubsection'].indexOf(match[1]!), title: match[2]!, path, line: index + 1 });
  });
  return items;
}

/** Edit distance, for “Gợi ý: gao2023survey” next to an unresolved key (EC26). */
export function distance(a: string, b: string): number {
  const row = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i += 1) {
    let previous = row[0]!;
    row[0] = i;
    for (let j = 1; j <= b.length; j += 1) {
      const current = row[j]!;
      row[j] = Math.min(row[j]! + 1, row[j - 1]! + 1, previous + (a[i - 1] === b[j - 1] ? 0 : 1));
      previous = current;
    }
  }
  return row[b.length]!;
}

export function nearestKey(key: string, candidates: readonly string[]): string | undefined {
  let best: string | undefined;
  let score = Infinity;
  for (const candidate of candidates) {
    const d = distance(key.toLowerCase(), candidate.toLowerCase());
    if (d < score) {
      best = candidate;
      score = d;
    }
  }
  return best !== undefined && score <= Math.max(2, Math.floor(key.length / 4)) ? best : undefined;
}

export type DiffLine = { kind: 'same' | 'add' | 'del'; text: string; oldLine?: number; newLine?: number };

/** Line diff (LCS) of two texts, computed in the browser to compare revisions (H14). */
export function lineDiff(before: string, after: string): DiffLine[] {
  const a = before.split('\n');
  const b = after.split('\n');
  const n = a.length;
  const m = b.length;
  const lcs: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) lcs[i]![j] = a[i] === b[j] ? lcs[i + 1]![j + 1]! + 1 : Math.max(lcs[i + 1]![j]!, lcs[i]![j + 1]!);
  }
  const out: DiffLine[] = [];
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) {
      out.push({ kind: 'same', text: a[i]!, oldLine: i + 1, newLine: j + 1 });
      i += 1;
      j += 1;
    } else if (j < m && (i >= n || lcs[i]![j + 1]! > lcs[i + 1]![j]!)) {
      // On a tie the removed line comes first, as in a unified diff.
      out.push({ kind: 'add', text: b[j]!, newLine: j + 1 });
      j += 1;
    } else {
      out.push({ kind: 'del', text: a[i]!, oldLine: i + 1 });
      i += 1;
    }
  }
  return out;
}

/** Applies a proposal's hunks to a file's text (the preview after accepting); null when they do not match. */
export function applyHunks(text: string, hunks: readonly Schemas['DiffHunk'][]): string | null {
  const lines = text.split('\n');
  let shift = 0;
  for (const hunk of [...hunks].sort((x, y) => (x.oldStart ?? 0) - (y.oldStart ?? 0))) {
    const start = Math.max(0, (hunk.oldStart ?? 1) - 1 + shift);
    const removed: string[] = [];
    const added: string[] = [];
    for (const line of hunk.lines ?? []) {
      if (line[0] === '-') removed.push(line.slice(1));
      else if (line[0] === '+') added.push(line.slice(1));
      else {
        removed.push(line.slice(1));
        added.push(line.slice(1));
      }
    }
    if (removed.some((line, index) => lines[start + index] !== line)) return null;
    lines.splice(start, removed.length, ...added);
    shift += added.length - removed.length;
  }
  return lines.join('\n');
}

const root = () => (typeof window === 'undefined' ? 'http://localhost' : window.location.origin);

/** GET of a non-JSON response through the API base (file content, build log, PDF, export); errors as ApiError. */
export async function rawGet(api: ApiClient, path: string, query?: Record<string, unknown>, signal?: AbortSignal): Promise<Response> {
  let response: Response;
  try {
    response = await fetch(new URL(api.url(path, query), root()), { credentials: 'same-origin', signal });
  } catch {
    throw new ApiError('network');
  }
  if (!response.ok) {
    const type = response.headers.get('content-type') ?? '';
    if (/json/.test(type)) {
      const problem = (await response.json().catch(() => undefined)) as Schemas['Problem'] | undefined;
      if (problem?.code) throw new ApiError('problem', { status: response.status, problem });
    }
    throw new ApiError('http', { status: response.status });
  }
  return response;
}

export const manuscriptPath = (projectId: string) => `/projects/${encodeURIComponent(projectId)}/manuscript`;
export const filePath = (projectId: string, fileId: string) => `${manuscriptPath(projectId)}/files/${encodeURIComponent(fileId)}/content`;

/** Text or bytes of a file at a revision (current when omitted), with its ETag (contentHash). */
export async function fileContent(api: ApiClient, projectId: string, file: Pick<ManuscriptFile, 'id' | 'path' | 'fileType'>, revisionId?: string) {
  const response = await rawGet(api, filePath(projectId, file.id), revisionId ? { revisionId } : undefined);
  const etag = response.headers.get('etag')?.replace(/^W\//, '').replace(/"/g, '') ?? undefined;
  if (isText(file)) return { text: await response.text(), etag };
  return { blob: await response.blob(), etag };
}

/** Saves a downloaded file under its server name (Content-Disposition) or `fallback`. */
export async function download(response: Response, fallback: string): Promise<void> {
  const disposition = response.headers.get('content-disposition') ?? '';
  const name = /filename="?([^";]+)"?/.exec(disposition)?.[1] ?? fallback;
  const blob = await response.blob();
  let url: string;
  try {
    url = URL.createObjectURL(blob);
  } catch {
    // No object URL (tests, very old browsers): nothing to save.
    return;
  }
  const link = document.createElement('a');
  link.href = url;
  link.download = name;
  link.rel = 'noopener';
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Number of pages of a PDF, read from its page objects (the preview's “Trang 1 / N”, H17); undefined if unknown. */
export async function pdfPageCount(blob: Blob): Promise<number | undefined> {
  try {
    const text = new TextDecoder('latin1').decode(await blob.arrayBuffer());
    const count = text.match(/\/Type\s*\/Page(?!s)/g)?.length ?? 0;
    return count || undefined;
  } catch {
    return undefined;
  }
}
